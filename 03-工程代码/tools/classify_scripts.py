def classify(num, title):
    body = title
    if num in LIT_MISC_NUMS:
        return "文献杂录", "序论杂文"
    if num in ZAJU_NUMS:
        genre = "元杂剧"
        motif = None
        for name, pat in ZAJU_RULES:
            if re.search(pat, body):
                motif = name
                break
        if motif is None:
            motif = "其他杂剧"
    elif num in QUBU_NUMS:
        genre = "散曲"
        # 「曲牌 (作者·首句)」格式 = 无独立题名 → 杂咏
        if re.search(r"\([^（）()]*·[^（）()]*\)$", body):
            motif = "杂咏（曲牌即题）"
        else:
            motif = None
            for name, pat in QUBU_RULES:
                if re.search(pat, body):
                    motif = name
                    break
            if motif is None:
                if "·" not in body and "‧" not in body:
                    motif = "杂咏（曲牌即题）"
                else:
                    motif = "其他散曲"
    elif num in CHUANQI_NUMS:
        genre = "明清传奇"
        motif = None
        for name, pat in CQ_RULES:
            if re.search(pat, body):
                motif = name
                break
        if motif is None:
            motif = "其他传奇"
    else:
        return "未知", "未分类"
    # MANUAL 只覆盖母题，文体保持原判定
    if num in MANUAL:
        motif = MANUAL[num]
    return genre, motif


def norm_title(fn):
    m = re.match(r"^(\d{4})_(.+)\.txt$", fn)
    if not m:
        return None, None
    num = int(m.group(1))
    title = m.group(2)
    # 去掉括注的作者（散曲区保留曲牌名）
    return num, title


def main():
    files = sorted(os.listdir(SRC))
    rows = []
    stats = OrderedDict()
    for fn in files:
        num, title = norm_title(fn)
        if num is None:
            continue
        genre, motif = classify(num, title)
        rows.append((num, title, genre, motif))
        key = (genre, motif)
        stats[key] = stats.get(key, 0) + 1

    # 统计
    print("=== 分文体统计 ===")
    genre_total = OrderedDict()
    for (g, m), c in stats.items():
        genre_total[g] = genre_total.get(g, 0) + c
    for g, c in genre_total.items():
        print(f"{g}: {c}")

    print("\n=== 母题细分统计 ===")
    for (g, m), c in sorted(stats.items()):
        print(f"{g} | {m} | {c}")

    # 台账表格行
    print("\n=== 台账表（按文体分组输出） ===")
    print("| 编号 | 篇名 | 文体 | 题材母题 |")
    print("| --- | --- | --- | --- |")
    for num, title, g, m in rows:
        print(f"| {num:04d} | {title} | {g} | {m} |")

    # 统计表格行（母题汇总）
    print("\n=== 母题汇总表 ===")
    print("| 文体 | 题材母题 | 篇数 | 代表篇目 |")
    print("| --- | --- | --- | --- |")
    for (g, m), c in sorted(stats.items(), key=lambda kv: (-kv[1], kv[0])):
        samples = [t for n, t, gg, mm in rows if gg == g and mm == m][:4]
        print(f"| {g} | {m} | {c} | {'、'.join(samples)} |")


if __name__ == "__main__":
    main()
