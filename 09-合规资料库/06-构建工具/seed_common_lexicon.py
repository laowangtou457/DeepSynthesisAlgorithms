def load_state(path):
    """返回 (保留的行列表, 已有词条集合, 原词条数)。"""
    if not os.path.exists(path):
        return [], set(), 0
    with open(path, encoding="utf-8") as f:
        raw = f.read()
    keep, existing = [], set()
    for ln in raw.split("\n"):
        s = ln.strip()
        if s.startswith("# 词条数"):
            continue
        if s and not s.startswith("#"):
            w = s.split("\t")[0].strip()
            if w:
                existing.add(w)
        keep.append(ln)
    while keep and not keep[-1].strip():
        keep.pop()
    return keep, existing, len(existing)


def process(cat_id, cat, groups, dry=False):
    path = os.path.join(VOCAB, cat["file"])
    keep, existing, before = load_state(path)
    added, out = 0, []
    for item in groups:
        sev, grp, words = item[0], item[1], item[2]
        note = item[3] if len(item) > 3 else None
        fresh = [w for w in words.split() if w and w not in existing]
        if not fresh:
            continue
        out.append("")
        out.append("# ===== %s =====" % grp)
        for w in fresh:
            existing.add(w)
            added += 1
            out.append("%s\t%s\t%s" % (w, sev, note) if note else "%s\t%s" % (w, sev))
    after = before + added
    if added and not dry:
        body = keep + out + ["", "# 词条数（不含注释）：%d / %d" % (after, cat["quota"]), ""]
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(body))
    cat["seed_count"] = after
    return before, after, added


