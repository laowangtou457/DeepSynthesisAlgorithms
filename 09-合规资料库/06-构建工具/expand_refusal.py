def load_jsonl(path):
    ids, mx, rows = set(), 0, []
    if not os.path.exists(path):
        return ids, mx, rows
    with open(path, encoding="utf-8") as f:
        for line in f:
            s = line.strip()
            if not s or s.startswith("#"):
                continue
            try:
                obj = json.loads(s)
            except Exception:
                continue
            rows.append(obj)
            ids.add(obj.get("id"))
            m = re.search(r"-(\d+)$", obj.get("id", ""))
            if m:
                mx = max(mx, int(m.group(1)))
    return ids, mx, rows


def find_cat(name):
    with open(os.path.join(ROOT, "01-关键词库", "lexicon_manifest.json"), encoding="utf-8") as f:
        mf = json.load(f)
    for c in mf["categories"]:
        if c["name"] == name:
            return c
    return None


